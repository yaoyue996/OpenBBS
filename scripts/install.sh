#!/usr/bin/env bash
# OpenBBS one-click installer for Linux and macOS.
#
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/yaoyue996/OpenBBS/main/scripts/install.sh | bash
#
# Optional environment variables:
#   OPENBBS_DIR        install directory (default: ~/openbbs)
#   OPENBBS_PORT       HTTP port (default: 3000)
#   OPENBBS_SITE_URL   public URL (default: http://localhost:$OPENBBS_PORT)
#   OPENBBS_BRANCH     git branch to download (default: main)
#   OPENBBS_NODE_VERSION  Node.js version to download when needed (default: 24.22.3)
#   OPENBBS_ADMIN_USERNAME / OPENBBS_ADMIN_EMAIL

set -euo pipefail

REPO="yaoyue996/OpenBBS"
BRANCH="${OPENBBS_BRANCH:-main}"
NODE_VERSION="${OPENBBS_NODE_VERSION:-24.22.3}"
INSTALL_DIR="${OPENBBS_DIR:-$HOME/openbbs}"
PORT="${OPENBBS_PORT:-3000}"
SITE_URL="${OPENBBS_SITE_URL:-http://localhost:$PORT}"
ADMIN_USERNAME="${OPENBBS_ADMIN_USERNAME:-admin}"
ADMIN_EMAIL="${OPENBBS_ADMIN_EMAIL:-admin@example.com}"

say() { printf '\033[1;36m[OpenBBS]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[OpenBBS] 错误：\033[0m %s\n' "$*" >&2; exit 1; }

for command in curl tar; do
  command -v "$command" >/dev/null 2>&1 || die "缺少命令 $command，请先安装后重试。"
done

if [ -f "$INSTALL_DIR/server.js" ]; then
  die "检测到已有安装：$INSTALL_DIR。更新请运行 bash \"$INSTALL_DIR/scripts/update.sh\"。"
fi

case "$(uname -s)" in
  Linux) PLATFORM="linux" ;;
  Darwin) PLATFORM="darwin" ;;
  *) die "当前系统不受支持：$(uname -s)。请使用 Docker 或手动安装。" ;;
esac

case "$(uname -m)" in
  x86_64|amd64) NODE_ARCH="x64" ;;
  aarch64|arm64) NODE_ARCH="arm64" ;;
  armv7l) NODE_ARCH="armv7l" ;;
  *) die "当前 CPU 架构不受支持：$(uname -m)。" ;;
esac

if [ "$PLATFORM" = "darwin" ] && [ "$NODE_ARCH" = "armv7l" ]; then
  die "macOS 不支持 armv7l。"
fi

mkdir -p "$INSTALL_DIR"
TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/openbbs-install.XXXXXX")"
cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT

say "下载 OpenBBS 源码（$BRANCH 分支）…"
curl -fsSL "https://codeload.github.com/$REPO/tar.gz/refs/heads/$BRANCH" -o "$TMP_DIR/openbbs.tar.gz" \
  || die "下载源码失败，请检查网络或仓库地址。"
tar -xzf "$TMP_DIR/openbbs.tar.gz" -C "$TMP_DIR"
SRC_DIR="$(find "$TMP_DIR" -maxdepth 1 -type d -name 'OpenBBS-*' | head -n 1)"
[ -n "$SRC_DIR" ] && [ -f "$SRC_DIR/server.js" ] || die "源码包结构不正确。"
cp -R "$SRC_DIR"/. "$INSTALL_DIR"/

# ---------------------------------------------------------------------------
# Node.js
# ---------------------------------------------------------------------------

node_ok() {
  command -v node >/dev/null 2>&1 || return 1
  node -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>22||(a===22&&b>=13)?0:1)' >/dev/null 2>&1
}

npm_ok() {
  command -v npm >/dev/null 2>&1
}

if ! node_ok || ! npm_ok; then
  say "系统 Node.js 不满足要求，正在下载 Node.js v$NODE_VERSION（本地安装，无需 root）…"
  NODE_DIST="node-v$NODE_VERSION-$PLATFORM-$NODE_ARCH"
  NODE_URL="https://nodejs.org/dist/v$NODE_VERSION/$NODE_DIST.tar.gz"
  mkdir -p "$INSTALL_DIR/.runtime"
  curl -fsSL "$NODE_URL" -o "$TMP_DIR/node.tar.gz" || die "下载 Node.js 失败：$NODE_URL"
  tar -xzf "$TMP_DIR/node.tar.gz" -C "$INSTALL_DIR/.runtime"
  rm -rf "$INSTALL_DIR/.runtime/node"
  mv "$INSTALL_DIR/.runtime/$NODE_DIST" "$INSTALL_DIR/.runtime/node"
fi

if [ -d "$INSTALL_DIR/.runtime/node/bin" ]; then
  export PATH="$INSTALL_DIR/.runtime/node/bin:$PATH"
fi
node_ok || die "Node.js 版本仍不满足要求（需要 >= 22.13）。"
command -v npm >/dev/null 2>&1 || die "未找到 npm。"

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

cd "$INSTALL_DIR"
if [ ! -f .env ]; then
  say "生成配置文件 .env…"
  cat > .env <<EOF
# Generated by OpenBBS installer on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
HOST=0.0.0.0
PORT=$PORT
SITE_URL=$SITE_URL
DATABASE_PATH=data/openbbs.db
TRUST_PROXY=0
COOKIE_SECURE=auto
NODE_ENV=production
ADMIN_USERNAME=$ADMIN_USERNAME
ADMIN_PASSWORD=
ADMIN_EMAIL=$ADMIN_EMAIL
EOF
  chmod 600 .env
fi

mkdir -p data
chmod +x scripts/*.sh 2>/dev/null || true

say "安装依赖（无需编译原生模块）…"
npm install --omit=dev --no-audit --no-fund

say "初始化数据库…"
npm run init

say "启动服务…"
bash scripts/service.sh start

printf '\n'
say "安装完成！"
printf '  访问地址:   http://localhost:%s\n' "$PORT"
printf '  安装目录:   %s\n' "$INSTALL_DIR"
printf '  初始管理员: %s（密码见 %s/data/initial-admin.txt）\n' "$ADMIN_USERNAME" "$INSTALL_DIR"
printf '\n'
printf '  常用命令:\n'
printf '    bash %s/scripts/service.sh status\n' "$INSTALL_DIR"
printf '    bash %s/scripts/service.sh restart\n' "$INSTALL_DIR"
printf '    bash %s/scripts/service.sh logs\n' "$INSTALL_DIR"
printf '    bash %s/scripts/update.sh\n' "$INSTALL_DIR"
printf '\n'
if [ "$SITE_URL" = "http://localhost:$PORT" ]; then
  printf '  提示：部署到公网时请编辑 %s/.env，把 SITE_URL 改成你的域名。\n' "$INSTALL_DIR"
fi
printf '  登录后请立即在「个人设置」中修改管理员密码。\n\n'
